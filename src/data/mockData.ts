const formatDate = (date: Date) => date.toISOString().split('T')[0];
const today = new Date();
const inDays = (d: number) => {
  const target = new Date();
  target.setDate(today.getDate() + d);
  return formatDate(target);
};
const pastDays = (d: number) => {
  const target = new Date();
  target.setDate(today.getDate() - d);
  return formatDate(target);
};

